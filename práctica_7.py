import numpy as np
import matplotlib.pyplot as plt
from skimage import io
from scipy.optimize import minimize
from skimage import measure

# Cargar imagen desde GitHub
img_url = "https://raw.githubusercontent.com/dilp90/PDI/main/Imagenes/Te-me_0015.jpg"
img = io.imread(img_url)

plt.figure(figsize=(6,6))
plt.imshow(img)
plt.axis('off')
plt.title('Imagen RGB original (desde GitHub)')
plt.show()

import cv2

# Convertir a RGB (por si viene en BGR)
if img.shape[2] == 3:
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
else:
    img_rgb = img

# Separar canales
R = img_rgb[:, :, 0]
G = img_rgb[:, :, 1]
B = img_rgb[:, :, 2]

# Normalizar canales entre 0 y 1
R_norm = R.astype(np.float32) / 255
G_norm = G.astype(np.float32) / 255
B_norm = B.astype(np.float32) / 255

print("R_norm:", R_norm.min(), R_norm.max())
print("G_norm:", G_norm.min(), G_norm.max())
print("B_norm:", B_norm.min(), B_norm.max())
print("Shape imagen:", img_rgb.shape)
print("Tipo de imagen:", img.dtype)

# --------------------------------------------------------
# FUNCION OBJETIVO (maximizar varianza -> minimizar negativo)
# --------------------------------------------------------
def grayscale_variance(weights):
    w_r, w_g, w_b = weights
    gray = w_r * R_norm + w_g * G_norm + w_b * B_norm
    gray_norm = (gray - gray.min()) / (gray.max() - gray.min() + 1e-8)
    return -np.var(gray_norm)

# Restricción: w_r + w_g + w_b = 1
constraints = ({'type': 'eq', 'fun': lambda w: np.sum(w) - 1})

# Límites de cada peso
bounds = [(0, 1), (0, 1), (0, 1)]

# Valor inicial
initial_weights = [0.33, 0.33, 0.34]

# Ejecución SLSQP
result = minimize(grayscale_variance,
                  initial_weights,
                  method='SLSQP',
                  bounds=bounds,
                  constraints=constraints)

optimal_weights = result.x
print("\n📌 Pesos óptimos:", optimal_weights)

# Imagen gris optimizada
wR, wG, wB = optimal_weights
gray_opt = wR*R_norm + wG*G_norm + wB*B_norm
gray_opt = (gray_opt - gray_opt.min()) / (gray_opt.max() - gray_opt.min() + 1e-8)

# Mostrar la imagen resultante
plt.figure(figsize=(5,5))
plt.imshow(gray_opt, cmap='gray')
plt.title("Imagen gris con pesos óptimos SLSQP")
plt.axis('off')
plt.show()

# Mostrar los canales por separado
plt.figure(figsize=(14, 4))

plt.subplot(1, 4, 1)
plt.imshow(img_rgb)
plt.title('Imagen original')
plt.axis('off')

plt.subplot(1, 4, 2)
plt.imshow(R, cmap='Reds')
plt.title('Canal Rojo')
plt.axis('off')

plt.subplot(1, 4, 3)
plt.imshow(G, cmap='Greens')
plt.title('Canal Verde')
plt.axis('off')

plt.subplot(1, 4, 4)
plt.imshow(B, cmap='Blues')
plt.title('Canal Azul')
plt.axis('off')

plt.show()

# Convertir a escala de grises promediando canales
gray_avg = ((R.astype(np.float32) + G + B) / 3).astype(np.uint8)

# Mostrar imagen en escala de grises
plt.imshow(gray_avg, cmap='gray')
plt.title('Escala de grises (promedio)')
plt.axis('off')
plt.show()

# Asegurar conversión BGR → RGB solo si viene en BGR
if img.shape[2] == 3:
    try:
        img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    except:
        img_rgb = img  # Si ya está en RGB, se deja igual
else:
    img_rgb = img

# Separación de canales
R, G, B = img_rgb[:, :, 0], img_rgb[:, :, 1], img_rgb[:, :, 2]

# Normalizar canales entre 0 y 1
R_norm = R.astype(np.float32) / 255
G_norm = G.astype(np.float32) / 255
B_norm = B.astype(np.float32) / 255

# Función objetivo: varianza negativa (porque minimize() minimiza)
def grayscale_variance(weights):
    w_r, w_g, w_b = weights
    gray = w_r * R_norm + w_g * G_norm + w_b * B_norm
    gray_normalized = (gray - gray.min()) / (gray.max() - gray.min())
    return -np.var(gray_normalized)  # Negativo para maximizar

# Restricción: suma de pesos debe ser 1
constraints = ({'type': 'eq', 'fun': lambda w: np.sum(w) - 1})

# Límites de cada peso: entre 0 y 1
bounds = [(0, 1), (0, 1), (0, 1)]

# Valor inicial
initial_weights = [0.33, 0.33, 0.34]

# Optimización
result = minimize(grayscale_variance, initial_weights, method='SLSQP',
                  bounds=bounds, constraints=constraints)

optimal_weights = result.x
print("Pesos óptimos:", optimal_weights)

# Crear imagen en escala de grises con pesos óptimos
gray_optimal = optimal_weights[0] * R_norm + optimal_weights[1] * G_norm + optimal_weights[2] * B_norm
gray_optimal = (gray_optimal * 255).astype(np.uint8)

# Mostrar resultado
# Imagen obtenida de manera directa o sencilla
plt.figure(figsize=(12, 4))
plt.subplot(1, 2, 1)
plt.imshow(gray_avg, cmap='gray')
plt.title('Escala de grises (promedio)')
plt.axis('off')

# Imagen obtenida de manera óptima
plt.subplot(1, 2, 2)
plt.imshow(gray_optimal, cmap='gray')
plt.title('Escala de grises con máximo contraste')
plt.axis('off')
plt.show()

# Segmentar ambas imágenes con un mismo umbral
umbral = 100
_, seg_standard = cv2.threshold(gray_avg, umbral, 255, cv2.THRESH_BINARY)
_, seg_optimal = cv2.threshold(gray_optimal, umbral, 255, cv2.THRESH_BINARY)

# Mostrar resultado
# Imagen obtenida de manera directa o sencilla
plt.figure(figsize=(12, 4))
plt.subplot(1, 2, 1)
plt.imshow(seg_standard, cmap='gray')
plt.title(f'Segmentación estándar (umbral={umbral})')
plt.axis('off')

# Imagen obtenida de manera óptima
plt.subplot(1, 2, 2)
plt.imshow(seg_optimal, cmap='gray')
plt.title(f'Segmentación óptima (umbral={umbral})')
plt.axis('off')
plt.show()

# -----------------------------------------
# Convertir la segmentación óptima a booleano
# -----------------------------------------
bw = seg_optimal.astype(bool)

# -----------------------------------------
# Limpiar ruido
# -----------------------------------------
bw_clean = bw.copy()

# Etiquetado
label_img = measure.label(bw_clean)
regions = measure.regionprops(label_img)

# -----------------------------------------
# SI NO HAY REGIONES
# -----------------------------------------
if len(regions) == 0:
    print('No se detectaron regiones tras limpiar la segmentación.')
else:
    regions_sorted = sorted(regions, key=lambda r: r.area, reverse=True)
    if len(regions_sorted) >= 2:
        skull_reg = regions_sorted[0]
        tumor_reg = regions_sorted[1]
    else:
        skull_reg = regions_sorted[0]
        tumor_reg = None

    # -----------------------------------------
    # Crear máscaras separadas
    # -----------------------------------------
    skull_mask = (label_img == skull_reg.label)
    tumor_mask = (label_img == tumor_reg.label) if tumor_reg else np.zeros_like(label_img, dtype=bool)

    # -----------------------------------------
    # Función para obtener contornos
    # -----------------------------------------
    def mask_to_contours(mask):
        mask_u8 = (mask.astype(np.uint8) * 255)
        contours, _ = cv2.findContours(mask_u8, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        return contours

    skull_cnts = mask_to_contours(skull_mask)
    tumor_cnts = mask_to_contours(tumor_mask)

    # -----------------------------------------
    # Mostrar contornos sobre la imagen original
    # -----------------------------------------
    fig, ax = plt.subplots(1, 1, figsize=(6, 6))
    ax.imshow(img_rgb)   # tu imagen original en color

    # contornos cráneo → rojo
    for cnt in skull_cnts:
        cnt = cnt.squeeze()
        ax.plot(cnt[:, 0], cnt[:, 1], '-r', linewidth=1)

    # contornos tumor → amarillo
    for cnt in tumor_cnts:
        cnt = cnt.squeeze()
        ax.plot(cnt[:, 0], cnt[:, 1], '-y', linewidth=2)

    ax.set_title('Contornos detectados: Rojo = Cráneo, Amarillo = Tumor')
    ax.axis('off')

    plt.show()

# Cálculo del área del tumor

if tumor_reg is not None:
    tumor_area_px = tumor_reg.area
    print(f'Área del tumor (en píxeles): {tumor_area_px}')

else:
    print('No se pudo determinar una región como tumor.')